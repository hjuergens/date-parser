"""Writes REPORT.md from the runs in results/<cpu>/run-*.json and the hand-written findings.md (see README.md):

    python3 benchmark/schedule/report.py
"""
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"c": "C, native", "go-swig": "Go → SWIG → C", "antlr-python": "ANTLR 4, Python target",
         "antlr-java": "ANTLR 4, Java target", "compiled": "ANTLR 4, Java, compiled to bytecode"}


def ms(seconds):
    return f"{seconds * 1000:,.1f}"


def main():
    machines = sorted(p for p in (HERE / "results").iterdir() if p.is_dir())
    lines = ["# Schedule language: C, Go via SWIG, and ANTLR's Python and Java targets", "",
             "Generated by `benchmark/schedule/report.py` from `results/`; the protocol is in [README.md](README.md).",
             "Times are the median of the timed rounds of all runs on a machine (min–max in brackets); "
             "per case is the median divided by the number of cases.", ""]
    checksums = {}   # commit -> checksums; the spec files grow, so only runs of one commit must agree
    for machine in machines:
        runs = [json.loads(p.read_text()) for p in sorted(machine.glob("run-*.json"))]
        if not runs:
            continue
        m, v = runs[0]["machine"], runs[0]["versions"]
        lines += [f"## {m['cpu']}", "",
                  f"{m['threads']} threads, {m['memory_gb']} GB visible to Linux, {m['os']}, Docker {m['docker']}. "
                  f"{len(runs)} runs of {runs[0]['rounds']} rounds each, commit {', '.join(sorted({r['commit'] for r in runs}))}.",
                  "", f"Tools: {v['cc']}; {v['go']}; {v['swig']}; Python {v['python']}, antlr4-python3-runtime {v['antlr4-runtime']}"
                  + (f"; {v['java']}" if "java" in v else "") + ".", "",
                  "| Implementation | Parse, ms per round | µs per case | vs C | Parse and evaluate, ms per round | µs per case | vs C | Start-up, ms | Evaluate only, µs per case |",
                  "|---|---|---|---|---|---|---|---|---|"]
        medians, parse_medians = {}, {}
        for name in NAMES:
            results = [r for run in runs for r in run["results"] if r["implementation"] == name]
            if not results:
                continue
            parse = [t for r in results for t in r["parse"]]
            evaluate = [t for r in results for t in r["evaluate"]]
            cases = results[0]["cases"]
            medians[name] = statistics.median(evaluate)
            parse_medians[name] = statistics.median(parse)
            for run in runs:
                for r in run["results"]:
                    if r["implementation"] == name:
                        checksums.setdefault(run["commit"], set()).add(json.dumps(r["checksum"], sort_keys=True))
            startup = statistics.median(r["startup_ms"] for r in results)
            only = [t for r in results for t in r.get("evaluate_only", [])]
            only = f"{statistics.median(only) / cases * 1e6:,.2f}" if only else "–"
            ratio = medians[name] / medians["c"] if "c" in medians else float("nan")
            parse_ratio = parse_medians[name] / parse_medians["c"] if "c" in parse_medians else float("nan")
            lines.append(f"| {NAMES[name]} | {ms(statistics.median(parse))} ({ms(min(parse))}–{ms(max(parse))}) "
                         f"| {statistics.median(parse) / cases * 1e6:,.1f} | {parse_ratio:,.1f}× "
                         f"| {ms(statistics.median(evaluate))} ({ms(min(evaluate))}–{ms(max(evaluate))}) "
                         f"| {statistics.median(evaluate) / cases * 1e6:,.1f} | {ratio:,.1f}× | {startup:,.1f} | {only} |")
        lines.append("")
    if all(len(c) == 1 for c in checksums.values()):
        lines += ["## Same work everywhere", "", "All implementations on all machines that ran a commit produced the same checksum:", ""]
        for commit, c in sorted(checksums.items()):
            c = json.loads(next(iter(c)))
            lines.append(f"- {commit}: {c['dates']} dates with a day-number sum of {c['sum']}, {c['errors']} cases with an "
                         f"error, {c['parse_errors']} inputs that don't parse.")
        lines.append("")
    else:
        lines += ["## Checksums differ", "", "The implementations did not all compute the same results:", ""]
        lines += [f"- {commit}: `{c}`" for commit, cs in sorted(checksums.items()) for c in sorted(cs)] + [""]
    findings = HERE / "findings.md"
    if findings.exists():
        lines += [findings.read_text(encoding="utf-8")]
    (HERE / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote", HERE / "REPORT.md")


if __name__ == "__main__":
    main()
