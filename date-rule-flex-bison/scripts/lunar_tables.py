"""Writes src/lunar_tables.h: the first day and the length of every Hijri (Umm al-Qura) and Chinese month that the
Python libraries of date-rule-lark know (hijridate: 1343 to 1500 AH, lunardate: 1900 to 2099, leap months left out).
Umm al-Qura is an observed calendar and the Chinese one depends on astronomy, so C gets them as data; the Hebrew
calendar is arithmetic and computed in calendars.c.

    uv run --project ../date-rule-lark python scripts/lunar_tables.py > src/lunar_tables.h
"""
from datetime import date

from hijridate import Hijri
from lunardate import LunarDate

EPOCH = date(1970, 1, 1).toordinal()


def day(d):
    return d.toordinal() - EPOCH


def chinese_length(year, month):
    try:
        LunarDate(year, month, 30).to_solar_date()
        return 30
    except ValueError:
        return 29


print("/* Generated by scripts/lunar_tables.py from hijridate and lunardate; don't edit. */")
print("/* { first day of the month (days since 1970-01-01), length } per year and month */")
print("enum { HIJRI_FIRST_YEAR = 1343, HIJRI_LAST_YEAR = 1500, CHINESE_FIRST_YEAR = 1900, CHINESE_LAST_YEAR = 2099 };")
print("static const int HIJRI_MONTHS[][12][2] = {")
for year in range(1343, 1501):
    months = [Hijri(year, m, 1) for m in range(1, 13)]
    print("    {" + ", ".join(f"{{{day(h.to_gregorian())}, {h.month_length()}}}" for h in months) + "},")
print("};")
print("static const int CHINESE_MONTHS[][12][2] = {")
for year in range(1900, 2100):
    print("    {" + ", ".join(f"{{{day(LunarDate(year, m, 1).to_solar_date())}, {chinese_length(year, m)}}}"
                          for m in range(1, 13)) + "},")
print("};")
