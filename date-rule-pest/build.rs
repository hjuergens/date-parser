//! Turns the tables of Umm al-Qura and Chinese months of the C module (date-rule-flex-bison/src/lunar_tables.h,
//! generated there from hijridate and lunardate) into Rust, so the two modules share one copy.

use std::{env, fs, path::Path};

const SOURCE: &str = "../date-rule-flex-bison/src/lunar_tables.h";

fn constant(text: &str, name: &str) -> i64 {
    let start = text.find(&format!("{name} = ")).unwrap_or_else(|| panic!("{name} in {SOURCE}")) + name.len() + 3;
    text[start..].split(|c: char| !c.is_ascii_digit()).next().unwrap().parse().unwrap()
}

/// the numbers of `static const int NAME[][12][2] = { ... };`, as Rust rows of 12 months of [first day, length]
fn table(text: &str, name: &str) -> String {
    let start = text.find(&format!("{name}[][12][2] = {{")).unwrap_or_else(|| panic!("{name} in {SOURCE}"));
    let body = &text[start..];
    let body = &body[body.find('=').unwrap() + 1..body.find("};").unwrap()];
    let numbers: Vec<i64> = body
        .split(|c: char| !(c.is_ascii_digit() || c == '-'))
        .filter(|s| !s.is_empty())
        .map(|s| s.parse().unwrap())
        .collect();
    assert_eq!(numbers.len() % 24, 0, "{name}: 12 months of 2 numbers per year");
    let rows: Vec<String> = numbers
        .chunks(24)
        .map(|year| {
            let months: Vec<String> = year.chunks(2).map(|m| format!("[{}, {}]", m[0], m[1])).collect();
            format!("    [{}],", months.join(", "))
        })
        .collect();
    format!("pub const {name}: &[[[i64; 2]; 12]] = &[\n{}\n];\n", rows.join("\n"))
}

fn main() {
    println!("cargo:rerun-if-changed={SOURCE}");
    let text = fs::read_to_string(SOURCE).expect(SOURCE);
    let mut out = String::from("// generated by build.rs from date-rule-flex-bison/src/lunar_tables.h\n");
    for name in ["HIJRI_FIRST_YEAR", "CHINESE_FIRST_YEAR", "CHINESE_LAST_YEAR"] {
        out += &format!("pub const {name}: i64 = {};\n", constant(&text, name));
    }
    out += &table(&text, "HIJRI_MONTHS");
    out += &table(&text, "CHINESE_MONTHS");
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("lunar_tables.rs"), out).unwrap();
}
